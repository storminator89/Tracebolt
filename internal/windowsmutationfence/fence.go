// Status contains only compact, non-secret blocking/recovery facts. An error
// always means blocked, even when no trustworthy owner can be recovered.
type Status struct {
	Active   bool   `json:"active"`
	Blocked  bool   `json:"blocked"`
	Domain   string `json:"domain,omitempty"`
	JobID    string `json:"jobId,omitempty"`
	Phase    string `json:"phase"`
	Recovery string `json:"recovery,omitempty"`
	Revision uint64 `json:"revision,string"`
	Retained int    `json:"retained"`
}

type storage interface {
	Read(string) ([]byte, error)
	Write(string, []byte) error
	Close() error
}
type opener func(bool) (storage, error)

// Session holds public immutable expectations only. Every transaction opens and
// closes a fresh fail-fast protected store. Close never releases a reservation.
type Session struct {
	mu         sync.Mutex
	roster     Roster
	domain     string
	now        func() time.Time
	open       opener
	closed     atomic.Bool
	capability *Capability
}

// Capability is issued only by a successful fresh Reserve. It is tied to this
// exact Session object, cannot be reconstructed from JSON or an existing owner,
// and is consumed before the final start callback. Never copy it by value.
type executionStart struct {
	started atomic.Bool
	at      atomic.Int64
}

type Capability struct {
	session        *Session
	owner          Owner
	reservation    uint64
	proof          string
	dispatchCalled bool
	dispatched     bool
	startCalled    bool
	start          *executionStart
	receipt        *Receipt
}

func (*Capability) String() string               { return "<one-use Windows mutation capability>" }
func (c *Capability) Format(f fmt.State, _ rune) { _, _ = io.WriteString(f, c.String()) }
func (*Capability) MarshalJSON() ([]byte, error) { return nil, ErrInvalid }
func (*Session) String() string                  { return "<Windows mutation fence session>" }

func validTime(n int64) bool    { return n > 0 && n <= 253402300799 }
func domainValid(d string) bool { return d == ManagedMSI || d == CachedWUA }
func (p Plan) Validate() error {
	if p.Version != "" && p.Version != ReusablePlanVersion && p.Version != BackgroundPlanVersion && p.Version != ReusableWUAPlanVersion {
		return ErrInvalid
	}
	if !enrollmentcrypto.ValidID(p.Identity.ManagerID, "manager_") || !enrollmentcrypto.ValidID(p.Identity.DeviceID, "agent_") || !actionpermit.ValidDigest(p.Identity.IncarnationDigest) {
		return ErrInvalid
	}
	for _, d := range []string{p.PlanDigest, p.MSIOfferDigest, p.WUAOfferDigest, p.MSIArtifactDigest, p.WUAArtifactDigest} {
		if !actionpermit.ValidDigest(d) {
			return ErrInvalid
		}
	}
	return nil
}
func (p Participant) valid(domain string) bool {
	return p.Domain == domain && actionpermit.ValidDigest(p.BindingDigest) && actionpermit.ValidDigest(p.GrantDigest) && actionpermit.ValidDigest(p.ManagerKeyDigest) && actionpermit.ValidDigest(p.ExecutorKeyDigest) && p.ManagerKeyDigest != p.ExecutorKeyDigest
}
func (r Roster) Validate() error {
	if !((r.Version == "" && r.Plan.Version == "") || (r.Version == ReusableRosterVersion && r.Plan.Version == ReusablePlanVersion) || (r.Version == BackgroundRosterVersion && r.Plan.Version == BackgroundPlanVersion) || (r.Version == ReusableWUARosterVersion && r.Plan.Version == ReusableWUAPlanVersion)) {
		return ErrInvalid
	}
	if r.Plan.Validate() != nil || !actionpermit.ValidDigest(r.FenceID) || !r.MSI.valid(ManagedMSI) || !r.WUA.valid(CachedWUA) || r.MSI.BindingDigest == r.WUA.BindingDigest || r.MSI.GrantDigest == r.WUA.GrantDigest {
		return ErrInvalid
	}
	seen := map[string]bool{}
	for _, d := range []string{r.MSI.ManagerKeyDigest, r.MSI.ExecutorKeyDigest, r.WUA.ManagerKeyDigest, r.WUA.ExecutorKeyDigest} {
		if seen[d] {
			return ErrInvalid
		}
		seen[d] = true
	}
	return nil
}
func digest(v any) string { raw, _ := json.Marshal(v); return actionpermit.Digest(raw) }
func (r Roster) Digest() string {
	if r.Validate() != nil {
		return ""
	}
	return digest(r)
}
func (a Activation) Validate() error {
	if a.Version != "" && a.Version != ReusableActivationVersion && a.Version != BackgroundActivationVersion && a.Version != ReusableWUAActivationVersion {
		return ErrInvalid
	}
	for _, d := range []string{a.MSIReceiptDigest, a.MSIConfigDigest, a.WUAReceiptDigest, a.WUAConfigDigest} {
		if !actionpermit.ValidDigest(d) {
			return ErrInvalid
		}
	}
	return nil
}
func (o Owner) Validate() error {
	if o.Sequence == 0 || !actionpermit.ValidDigest(o.PermitDigest) {
		return ErrInvalid
	}
	switch o.Domain {
	case ManagedMSI:
		if !enrollmentcrypto.ValidID(o.JobID, "transfer_") || o.TransferID != o.JobID {
			return ErrInvalid
		}
	case CachedWUA:
		if !enrollmentcrypto.ValidID(o.JobID, "update_") || o.TransferID != "" {
			return ErrInvalid
		}
	default:
		return ErrInvalid
	}
	return nil
}
func validReceiptOutcome(version, domain, outcome string) bool {
	return outcome == "completed" || version == ReusableWUAVersion && domain == CachedWUA && outcome == "succeeded"
}
func (r Receipt) Validate() error {
	if (r.Version != Version && r.Version != ReusableVersion && r.Version != BackgroundVersion && r.Version != ReusableWUAVersion) || !actionpermit.ValidDigest(r.FenceID) || !actionpermit.ValidDigest(r.RosterDigest) || r.Owner.Validate() != nil || r.Reservation == 0 || !actionpermit.ValidDigest(r.ResultDigest) || !validReceiptOutcome(r.Version, r.Owner.Domain, r.Outcome) || !validTime(r.CompletedAt) || !r.NativeReturned || !r.CleanupComplete || len(r.proof) != 64 {
		return ErrInvalid
	}
	b, e := hex.DecodeString(r.proof)
	if e != nil || hex.EncodeToString(b) != r.proof {
		return ErrInvalid
	}
	return nil
}

func validate(r record) error {
	if r.RetiredWUASequence != 0 && r.Activation == nil || r.Version != ReusableWUAVersion && (r.RetiredWUASequence != 0 || r.RetiredWUADigest != "" || r.RetiredWUAReceiptDigest != "") || (r.RetiredWUASequence == 0) != (r.RetiredWUADigest == "") || (r.RetiredWUASequence == 0) != (r.RetiredWUAReceiptDigest == "") || r.RetiredWUADigest != "" && !actionpermit.ValidDigest(r.RetiredWUADigest) || r.RetiredWUAReceiptDigest != "" && !actionpermit.ValidDigest(r.RetiredWUAReceiptDigest) {
		return ErrIntegrity
	}
	if (r.Version != Version && r.Version != ReusableVersion && r.Version != BackgroundVersion && r.Version != ReusableWUAVersion) || r.Version != planStateVersion(r.Plan.Version) || r.Version == Version && (r.RetiredMSISequence != 0 || r.RetiredMSIDigest != "") || (r.RetiredMSISequence == 0) != (r.RetiredMSIDigest == "") || r.RetiredMSIDigest != "" && !actionpermit.ValidDigest(r.RetiredMSIDigest) || r.Plan.Validate() != nil || !actionpermit.ValidDigest(r.FenceID) || r.Revision == 0 || !validTime(r.ClockFloor) || r.Entries == nil || len(r.Entries) > MaxOwners {
		return ErrIntegrity
	}
	if r.Roster == nil {
		if r.Activation != nil || len(r.Entries) != 0 {
			return ErrIntegrity
		}
	} else if r.Roster.Validate() != nil || r.Roster.Plan != r.Plan || r.Roster.FenceID != r.FenceID {
		return ErrIntegrity
	}
	if r.Activation != nil && (r.Activation.Validate() != nil || activationStateVersion(r.Activation.Version) != r.Version) || r.Activation == nil && len(r.Entries) != 0 {
		return ErrIntegrity
	}
	floors := map[string]uint64{ManagedMSI: r.RetiredMSISequence, CachedWUA: r.RetiredWUASequence}
	counts := map[string]int{}
	ids := map[string]bool{}
	permits := map[string]bool{}
	var lastRevision uint64
	var previousCompleted int64
	for i, e := range r.Entries {
		if e.Owner.Validate() != nil || e.Reservation <= lastRevision || e.Reservation > r.Revision || !validTime(e.ReservedAt) || e.ReservedAt > r.ClockFloor || e.ReservedAt < previousCompleted || !actionpermit.ValidDigest(e.ProofDigest) || e.Owner.Sequence <= floors[e.Owner.Domain] || ids[e.Owner.Domain+e.Owner.JobID] || permits[e.Owner.PermitDigest] {
			return ErrIntegrity
		}
		lastRevision = e.Reservation
		floors[e.Owner.Domain] = e.Owner.Sequence
		ids[e.Owner.Domain+e.Owner.JobID] = true
		permits[e.Owner.PermitDigest] = true
		counts[e.Owner.Domain]++
		if counts[ManagedMSI] > 1 || counts[CachedWUA] > 32 {
			return ErrIntegrity
		}
		if e.Phase != "released" && i != len(r.Entries)-1 {
			return ErrIntegrity
		}
		switch e.Phase {
		case "reserved":
			if e.DispatchedAt != 0 || e.StartCheckedAt != 0 || e.CompletedAt != 0 || e.ReceiptDigest != "" {
				return ErrIntegrity
			}
		case "dispatch_intent":
			if !validTime(e.DispatchedAt) || e.DispatchedAt < e.ReservedAt || e.DispatchedAt > r.ClockFloor || e.StartCheckedAt != 0 && (!validTime(e.StartCheckedAt) || e.StartCheckedAt < e.DispatchedAt || e.StartCheckedAt > r.ClockFloor) || e.CompletedAt != 0 || e.ReceiptDigest != "" {
				return ErrIntegrity
			}
		case "completion_recorded", "released":
			if !validTime(e.DispatchedAt) || e.DispatchedAt < e.ReservedAt || !validTime(e.StartCheckedAt) || e.StartCheckedAt < e.DispatchedAt || !validTime(e.CompletedAt) || e.CompletedAt < e.StartCheckedAt || e.CompletedAt > r.ClockFloor || !actionpermit.ValidDigest(e.ReceiptDigest) {
				return ErrIntegrity
			}
		default:
			return ErrIntegrity
		}
		previousCompleted = e.CompletedAt
	}
	return nil
}
func decode(raw []byte) (record, error) {
	var r record
	if len(raw) == 0 || len(raw) > MaxBytes || json.Unmarshal(raw, &r) != nil || validate(r) != nil {
		return record{}, ErrIntegrity
	}
	canonical, _ := json.Marshal(r)
	if !bytes.Equal(raw, canonical) {
		return record{}, ErrIntegrity
	}
	return r, nil
}
func save(s storage, r record) error {
	if validate(r) != nil {
		return ErrIntegrity
	}
	raw, e := json.Marshal(r)
	if e != nil || len(raw) > MaxBytes {
		return ErrIntegrity
	}
	if s.Write(stateFile, raw) != nil {
		return ErrUncertain
	}
	return nil
}

// RootPath has no caller-supplied path or environment-variable override.
func RootPath() (string, error) {
	l, e := windowsservice.ResolveLayout()
	if e != nil {
		return "", e
	}
	return l.ProgramData + `\Tracebolt\windows-mutation-fence`, nil
}
func StoreOptions() windowsstate.Options {
	return windowsstate.Options{InstallerOnly: true, Names: []string{stateFile}, LockName: "fence.lock", TempName: "fence.tmp", MaxBytes: MaxBytes}
}
func nativeOpen(create bool) (storage, error) {
	p, e := RootPath()
	if e != nil {
		return nil, e
	}
	o := StoreOptions()
	o.Create = create
	return windowsstate.Open(p, o)
}
func beginSetup(ctx context.Context, p Plan, now int64, open opener) (id string, err error) {
	if ctx == nil || p.Validate() != nil || !validTime(now) || open == nil {
		return "", ErrInvalid
	}
	if e := ctx.Err(); e != nil {
		return "", e
	}
	var nonce [32]byte
	if _, e := rand.Read(nonce[:]); e != nil {
		return "", ErrUnavailable
	}
	id = actionpermit.Digest(nonce[:])
	clear(nonce[:])
	s, e := open(true)
	if e != nil {
		return "", ErrUnavailable
	}
	defer func() {
		if s.Close() != nil {
			id = ""
			err = ErrUncertain
		}
	}()
	if e = ctx.Err(); e != nil {
		return "", e
	}
	r := record{Version: Version, Plan: p, FenceID: id, Revision: 1, ClockFloor: now, Entries: []entry{}}
	r.Version = planStateVersion(p.Version)
	if e = save(s, r); e != nil {
		return "", e
	}
	return id, nil
}

// BeginSetup creates only the fixed fresh root, recording permanent intent before
// either participant activates. Failure leaves evidence in place. No runtime
// path calls this function; callers need separately approved native setup.
func BeginSetup(ctx context.Context, p Plan, now int64) (string, error) {
	return beginSetup(ctx, p, now, nativeOpen)
}

// setupChange is a one-shot, short transaction. Neither staging nor activation
// can be repeated or used to repair missing/partial/replaced state.
func setupChange(ctx context.Context, roster Roster, a *Activation, now int64, open opener) (err error) {
	if ctx == nil || roster.Validate() != nil || !validTime(now) || a != nil && a.Validate() != nil {
		return ErrInvalid
	}
	if e := ctx.Err(); e != nil {
		return e
	}
	s, e := open(false)
	if e != nil {
		return ErrUnavailable
	}
	defer func() {
		if s.Close() != nil {
			err = ErrUncertain
		}
	}()
	if e = ctx.Err(); e != nil {
		return e
	}
	raw, e := s.Read(stateFile)
	if e != nil {
		return ErrIntegrity
	}
	r, e := decode(raw)
	if e != nil {
		return e
	}
	if r.Plan != roster.Plan || r.FenceID != roster.FenceID || now < r.ClockFloor || r.Revision == ^uint64(0) {
		return ErrIntegrity
	}
	if a != nil && activationStateVersion(a.Version) != r.Version {
		return ErrInvalid
	}
	if a == nil {
		if r.Roster != nil || r.Activation != nil {
			return ErrConsumed
		}
		r.Roster = &roster
	} else {
		if r.Roster == nil || *r.Roster != roster || r.Activation != nil {
			return ErrInactive
		}
		r.Activation = a
	}
	r.ClockFloor = now
	r.Revision++
	return save(s, r)
}
func BindRoster(ctx context.Context, r Roster, now int64) error {
	return setupChange(ctx, r, nil, now, nativeOpen)
}

// Activate may be called only after independently verifying both exact staged
// participant receipts/configs and still-current coordinated setup authority.
// The caller supplies their exact digests. This does not start either executor.
func Activate(ctx context.Context, r Roster, a Activation, now int64) error {
	return setupChange(ctx, r, &a, now, nativeOpen)
}

func openSession(ctx context.Context, r Roster, domain string, now func() time.Time, open opener) (*Session, error) {
	if ctx == nil || r.Validate() != nil || !domainValid(domain) || now == nil || open == nil {
		return nil, ErrInvalid
	}
	s := &Session{roster: r, domain: domain, now: now, open: open}
	if e := s.transaction(ctx, func(*record, int64) (bool, error) { return false, nil }); e != nil {
		return nil, e
	}
	return s, nil
}
func Open(ctx context.Context, r Roster, domain string, now func() time.Time) (*Session, error) {
	return openSession(ctx, r, domain, now, nativeOpen)
}

// transaction requires the session mutex after construction. windowsstate owns
// the cross-process lock only here; no user callback or domain ledger is read.
func (s *Session) transaction(ctx context.Context, fn func(*record, int64) (bool, error)) (err error) {
	if ctx == nil || s == nil || s.closed.Load() {
		return ErrUnavailable
	}
	if e := ctx.Err(); e != nil {
		return e
	}
	store, e := s.open(false)
	if e != nil {
		return ErrUnavailable
	}
	defer func() {
		if store.Close() != nil {
			err = ErrUncertain
		}
	}()
	if e = ctx.Err(); e != nil {
		return e
	}
	raw, e := store.Read(stateFile)
	if e != nil {
		return ErrIntegrity
	}
	r, e := decode(raw)
	if e != nil {
		return e
	}
	if r.Roster == nil || *r.Roster != s.roster || r.Plan != s.roster.Plan || r.FenceID != s.roster.FenceID {
		return ErrIntegrity
	}
	if r.Activation == nil {
		return ErrInactive
	}
	now := s.now().Unix()
	if !validTime(now) || now < r.ClockFloor {
		return ErrIntegrity
	}
	write, e := fn(&r, now)
	if e != nil {
		return e
	}
	if !write {
		return nil
	}
	if r.Revision == ^uint64(0) {
		return ErrIntegrity
	}
	r.Revision++
	r.ClockFloor = now
	return save(store, r)
}
func (s *Session) Close() error {
	if s == nil {
		return nil
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	s.closed.Store(true)
	return nil
}
func (s *Session) Reserve(ctx context.Context, o Owner) (*Capability, error) {
	if s == nil || o.Validate() != nil {
		return nil, ErrInvalid
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	if o.Domain != s.domain {
		return nil, ErrInvalid
	}
	var nonce [32]byte
	if _, e := rand.Read(nonce[:]); e != nil {
		return nil, ErrUnavailable
	}
	proof := hex.EncodeToString(nonce[:])
	clear(nonce[:])
	c := &Capability{session: s, owner: o, proof: proof, start: &executionStart{}}
	e := s.transaction(ctx, func(r *record, now int64) (bool, error) {
		if len(r.Entries) > 0 && r.Entries[len(r.Entries)-1].Phase != "released" {
			return false, ErrBusy
		}
		if o.Domain == ManagedMSI && o.Sequence <= r.RetiredMSISequence || o.Domain == CachedWUA && o.Sequence <= r.RetiredWUASequence {
			return false, ErrConsumed
		}
		count := 0
		for _, v := range r.Entries {
			if v.Owner.Domain == o.Domain {
				count++
				if v.Owner.JobID == o.JobID || v.Owner.Sequence >= o.Sequence {
					return false, ErrConsumed
				}
			}
			if v.Owner.PermitDigest == o.PermitDigest {
				return false, ErrConsumed
			}
		}
		if len(r.Entries) >= MaxOwners || o.Domain == ManagedMSI && count >= 1 || o.Domain == CachedWUA && count >= 32 {
			return false, ErrCapacity
		}
		if r.Revision == ^uint64(0) {
			return false, ErrIntegrity
		}
		c.reservation = r.Revision + 1
		r.Entries = append(r.Entries, entry{Owner: o, Reservation: c.reservation, ReservedAt: now, Phase: "reserved", ProofDigest: actionpermit.Digest([]byte(proof))})
		return true, nil
	})
	if e != nil {
		return nil, e
	}
	s.capability = c
	return c, nil
}
func (s *Session) owned(r *record, c *Capability) (*entry, error) {
	if c == nil || c.session != s || s.capability != c || len(r.Entries) == 0 {
		return nil, ErrConsumed
	}
	e := &r.Entries[len(r.Entries)-1]
	if e.Owner != c.owner || e.Reservation != c.reservation || e.ProofDigest != actionpermit.Digest([]byte(c.proof)) || e.Phase == "released" {
		return nil, ErrConsumed
	}
	return e, nil
}
func (s *Session) Dispatch(ctx context.Context, c *Capability) error {
	if s == nil {
		return ErrInvalid
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	if c == nil || c.session != s || s.capability != c || c.dispatchCalled || c.startCalled {
		return ErrConsumed
	}
	e := s.transaction(ctx, func(r *record, now int64) (bool, error) {
		v, e := s.owned(r, c)
		if e != nil {
			return false, e
		}
		if v.Phase != "reserved" {
			return false, ErrConsumed
		}
		v.Phase = "dispatch_intent"
		v.DispatchedAt = now
		return true, nil
	})
	// An uncertain dispatch write never permits another attempt in this process.
	c.dispatchCalled = true
	c.dispatched = e == nil
	return e
}

// CheckStart consumes the one-use capability, checks the exact durable dispatch
// owner, closes the protected transaction, then invokes finalAuthority. Therefore
// that callback sees time/identity/revocation changes after every storage wait.
// The callback must perform the domain's final current-leaf/consent/deadline/
// maintenance checks. A failure never grants a retry or an automatic release.
func (s *Session) CheckStart(ctx context.Context, c *Capability, finalAuthority func() error) error {
	if s == nil || finalAuthority == nil {
		return ErrInvalid
	}
	s.mu.Lock()
	if c == nil || c.session != s || s.capability != c || !c.dispatched || c.startCalled {
		s.mu.Unlock()
		return ErrConsumed
	}
	c.startCalled = true
	var observed int64
	e := s.transaction(ctx, func(r *record, now int64) (bool, error) {
		v, e := s.owned(r, c)
		if e != nil {
			return false, e
		}
		if v.Phase != "dispatch_intent" {
			return false, ErrConsumed
		}
		if v.StartCheckedAt != 0 {
			return false, ErrConsumed
		}
		v.StartCheckedAt = now
		observed = now
		return true, nil
	})
	s.mu.Unlock()
	if e != nil {
		return e
	}
	if e = ctx.Err(); e != nil {
		return e
	}
	if e = finalAuthority(); e != nil {
		return e
	}
	if e = ctx.Err(); e != nil {
		return e
	}
	// Do not reacquire the session mutex here. Another status/storage operation
	// could wait after finalAuthority checked the original start deadline. These
	// atomic stores publish completion eligibility without a post-check wait.
	if s.closed.Load() {
		return ErrUnavailable
	}
	now := s.now().Unix()
	if !validTime(now) || now < observed {
		return ErrIntegrity
	}
	c.start.at.Store(now)
	c.start.started.Store(true)
	return nil
}

// Completion is called only after synchronous native return and successful
// owner cleanup have been established, and before saving this receipt together
// with the domain result. Uncertain native work, timeout, or cleanup failure must
// not call it. Legacy/MSI receipts use "completed" without a success claim.
// Fresh v4 WUA may use "succeeded" only after exact successful domain result
// validation; that narrower outcome is required for explicit retirement.
func (c *Capability) Completion(resultDigest, outcome string, completedAt int64) (Receipt, error) {
	if c == nil || c.session == nil {
		return Receipt{}, ErrInvalid
	}
	s := c.session
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.closed.Load() || s.capability != c || !c.start.started.Load() || !actionpermit.ValidDigest(resultDigest) || !validReceiptOutcome(planStateVersion(s.roster.Plan.Version), c.owner.Domain, outcome) || !validTime(completedAt) || completedAt < c.start.at.Load() {
		return Receipt{}, ErrInvalid
	}
	r := Receipt{Version: Version, FenceID: s.roster.FenceID, RosterDigest: s.roster.Digest(), Owner: c.owner, Reservation: c.reservation, ResultDigest: resultDigest, Outcome: outcome, CompletedAt: completedAt, NativeReturned: true, CleanupComplete: true, proof: c.proof}
	r.Version = planStateVersion(s.roster.Plan.Version)
	if c.receipt != nil {
		if *c.receipt != r {
			return Receipt{}, ErrConsumed
		}
		return r, nil
	}
	c.receipt = &r
	return r, nil
}

func (s *Session) Complete(ctx context.Context, c *Capability, r Receipt, verify VerifyReceipt) error {
	if s == nil || c == nil {
		return ErrInvalid
	}
	s.mu.Lock()
	valid := c.session == s && s.capability == c && c.start.started.Load() && c.receipt != nil && *c.receipt == r
	s.mu.Unlock()
	if !valid {
		return ErrConsumed
	}
	return s.Recover(ctx, r, verify)
}

// Recover finishes only release using an exact saved terminal receipt. It never
// creates a Capability, runs native work, edits domain results or clears an owner
// on elapsed time, service exit, process disappearance, or reboot.
func (s *Session) Recover(ctx context.Context, r Receipt, verify VerifyReceipt) error {
	if s == nil || ctx == nil || r.Validate() != nil || verify == nil {
		return ErrInvalid
	}
	if r.Version != planStateVersion(s.roster.Plan.Version) || r.Owner.Domain != s.domain || r.FenceID != s.roster.FenceID || r.RosterDigest != s.roster.Digest() {
		return ErrIntegrity
	}
	if e := ctx.Err(); e != nil {
		return e
	}
	if e := verify(r); e != nil {
		return e
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	// First retain the exact domain completion evidence. A crash or failed close
	// here leaves completion_recorded, which only this exact receipt can release.
	e := s.transaction(ctx, func(state *record, now int64) (bool, error) {
		for i := range state.Entries {
			v := &state.Entries[i]
			if v.Owner != r.Owner || v.Reservation != r.Reservation {
				continue
			}
			if v.ProofDigest != actionpermit.Digest([]byte(r.proof)) || v.StartCheckedAt == 0 || r.CompletedAt < v.StartCheckedAt || r.CompletedAt > now {
				return false, ErrIntegrity
			}
			if v.Phase == "released" || v.Phase == "completion_recorded" {
				if v.ReceiptDigest != digest(r) || v.CompletedAt != r.CompletedAt {
					return false, ErrIntegrity
				}
				return false, nil
			}
			if i != len(state.Entries)-1 || v.Phase != "dispatch_intent" {
				return false, ErrUncertain
			}
			v.Phase = "completion_recorded"
			v.ReceiptDigest = digest(r)
			v.CompletedAt = r.CompletedAt
			return true, nil
		}
		return false, ErrIntegrity
	})
	if e != nil {
		return e
	}
	// No deferred release: only a second verified transaction changes ownership.
	return s.transaction(ctx, func(state *record, _ int64) (bool, error) {
		for i := range state.Entries {
			v := &state.Entries[i]
			if v.Owner != r.Owner || v.Reservation != r.Reservation {
				continue
			}
			if v.ReceiptDigest != digest(r) || v.CompletedAt != r.CompletedAt {
				return false, ErrIntegrity
			}
			if v.Phase == "released" {
				return false, nil
			}
			if i != len(state.Entries)-1 || v.Phase != "completion_recorded" {
				return false, ErrUncertain
			}
			v.Phase = "released"
			return true, nil
		}
		return false, ErrIntegrity
	})
}
func (s *Session) Status(ctx context.Context) (Status, error) {
	st := Status{Blocked: true, Phase: "unavailable", Recovery: "intervention_required"}
	if s == nil {
		return st, ErrUnavailable
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	e := s.transaction(ctx, func(r *record, _ int64) (bool, error) {
		st = Status{Active: true, Phase: "idle", Revision: r.Revision, Retained: len(r.Entries)}
		if len(r.Entries) > 0 {
			v := r.Entries[len(r.Entries)-1]
			if v.Phase != "released" {
				st.Blocked = true
				st.Domain = v.Owner.Domain
				st.JobID = v.Owner.JobID
				st.Phase = v.Phase
				st.Recovery = "intervention_required"
				if v.Phase == "completion_recorded" {
					st.Recovery = "exact_terminal_receipt"
				}
			}
		}
		return false, nil
	})
	if e != nil {
		st = Status{Blocked: true, Phase: "unavailable", Recovery: "intervention_required"}
	}
	return st, e
}

// Matches checks only the immutable public configuration, not current storage.
// Use Verify for a fresh active-roster check after any blocking work.
func (s *Session) Matches(r Roster, domain string) bool {
	if s == nil {
		return false
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	return !s.closed.Load() && s.roster == r && s.domain == domain
}
func (s *Session) Verify(ctx context.Context) error {
	if s == nil {
		return ErrUnavailable
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.transaction(ctx, func(*record, int64) (bool, error) { return false, nil })
}

// Validate rejects ambiguous or secret-bearing public snapshots. The zero value
// is not an idle assertion; unavailable state is explicitly blocked.
func (st Status) Validate() error {
	if !st.Active {
		if !st.Blocked || st.Phase != "unavailable" || st.Recovery != "intervention_required" || st.Domain != "" || st.JobID != "" || st.Revision != 0 || st.Retained != 0 {
			return ErrInvalid
		}
		return nil
	}
	if st.Revision == 0 || st.Retained < 0 || st.Retained > MaxOwners {
		return ErrInvalid
	}
	if !st.Blocked {
		if st.Phase != "idle" || st.Domain != "" || st.JobID != "" || st.Recovery != "" {
			return ErrInvalid
		}
		return nil
	}
	if !domainValid(st.Domain) || st.Retained == 0 {
		return ErrInvalid
	}
	prefix := "update_"
	if st.Domain == ManagedMSI {
		prefix = "transfer_"
	}
	if !enrollmentcrypto.ValidID(st.JobID, prefix) {
		return ErrInvalid
	}
	switch st.Phase {
	case "reserved", "dispatch_intent":
		if st.Recovery != "intervention_required" {
			return ErrInvalid
		}
	case "completion_recorded":
		if st.Recovery != "exact_terminal_receipt" {
			return ErrInvalid
		}
	default:
		return ErrInvalid
	}
	return nil
}

// VerifyParticipant additionally checks this domain's exact independent public
// configuration and completed setup receipt against immutable activation pins.
// The caller reads its own protected files before this short fence transaction.
func (s *Session) VerifyParticipant(ctx context.Context, configDigest, receiptDigest string) error {
	if s == nil || !actionpermit.ValidDigest(configDigest) || !actionpermit.ValidDigest(receiptDigest) {
		return ErrInvalid
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.transaction(ctx, func(r *record, _ int64) (bool, error) {
		expectedConfig, expectedReceipt := r.Activation.MSIConfigDigest, r.Activation.MSIReceiptDigest
		if s.domain == CachedWUA {
			expectedConfig, expectedReceipt = r.Activation.WUAConfigDigest, r.Activation.WUAReceiptDigest
		}
		if configDigest != expectedConfig || receiptDigest != expectedReceipt {
			return false, ErrIntegrity
		}
		return false, nil
	})
}

func verifyStaged(ctx context.Context, roster Roster, open opener) (err error) {
	if ctx == nil || roster.Validate() != nil || open == nil {
		return ErrInvalid
	}
	if e := ctx.Err(); e != nil {
		return e
	}
	s, e := open(false)
	if e != nil {
		return ErrUnavailable
	}
	defer func() {
		if s.Close() != nil {
			err = ErrUncertain
		}
	}()
	if e = ctx.Err(); e != nil {
		return e
	}
	raw, e := s.Read(stateFile)
	if e != nil {
		return ErrIntegrity
	}
	r, e := decode(raw)
	if e != nil {
		return e
	}
	if r.Roster == nil || *r.Roster != roster || r.Plan != roster.Plan || r.FenceID != roster.FenceID {
		return ErrIntegrity
	}
	if r.Activation != nil || len(r.Entries) != 0 {
		return ErrConsumed
	}
	return nil
}

// VerifyStaged is a read-only coordinated-setup guard. It requires the exact
// bound roster still inactive; it confers no runtime or mutation authority.
func VerifyStaged(ctx context.Context, r Roster) error { return verifyStaged(ctx, r, nativeOpen) }

// RetireMSI compacts only the exact released MSI owner after an explicit reviewed
// retirement. Its monotonic sequence floor and digest survive forever. WUA
// history is unchanged; no missing owner, timeout or unknown outcome can retire.
func (s *Session) RetireMSI(ctx context.Context, r Receipt, verify VerifyReceipt) error {
	if s == nil || ctx == nil || !s.roster.ReusableMSI() || s.domain != ManagedMSI || r.Version != planStateVersion(s.roster.Plan.Version) || r.Validate() != nil || r.Owner.Domain != ManagedMSI || r.FenceID != s.roster.FenceID || r.RosterDigest != s.roster.Digest() || verify == nil {
		return ErrInvalid
	}
	if e := verify(r); e != nil {
		return e
	}
	if e := ctx.Err(); e != nil {
		return e
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.transaction(ctx, func(state *record, _ int64) (bool, error) {
		if r.Owner.Sequence <= state.RetiredMSISequence {
			return false, ErrConsumed
		}
		for i, v := range state.Entries {
			if v.Owner != r.Owner || v.Reservation != r.Reservation {
				continue
			}
			if v.Phase != "released" || v.ReceiptDigest != digest(r) || v.CompletedAt != r.CompletedAt || v.ProofDigest != actionpermit.Digest([]byte(r.proof)) {
				return false, ErrUncertain
			}
			state.RetiredMSISequence = r.Owner.Sequence
			state.RetiredMSIDigest = actionpermit.Digest([]byte("Tracebolt retired Windows MSI owner v2\x00" + state.RetiredMSIDigest + "\x00" + digest(v)))
			state.Entries = append(state.Entries[:i], state.Entries[i+1:]...)
			return true, nil
		}
		return false, ErrIntegrity
	})
}

// RetireWUA compacts only the exact released cached-WUA owner after explicit
// result-bound retirement. In addition to VerifyReceipt's saved-evidence checks,
// its verifier must prove the domain result was successful and settled. Failed,
// partial, uncertain or pre-native outcomes must not retire. This preserves a
// permanent monotonic replay floor and exact-owner digest chain without extending
// the original consent, reconstructing authority or pruning another owner.
func (s *Session) RetireWUA(ctx context.Context, r Receipt, verify VerifyReceipt) error {
	if s == nil || ctx == nil || !s.roster.ReusableWUA() || s.domain != CachedWUA || r.Version != planStateVersion(s.roster.Plan.Version) || r.Validate() != nil || r.Outcome != "succeeded" || r.Owner.Domain != CachedWUA || r.FenceID != s.roster.FenceID || r.RosterDigest != s.roster.Digest() || verify == nil {
		return ErrInvalid
	}
	if e := verify(r); e != nil {
		return e
	}
	if e := ctx.Err(); e != nil {
		return e
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.transaction(ctx, func(state *record, _ int64) (bool, error) {
		if len(state.Entries) > 0 && state.Entries[len(state.Entries)-1].Phase != "released" {
			return false, ErrBusy
		}
		if r.Owner.Sequence == state.RetiredWUASequence && digest(r) == state.RetiredWUAReceiptDigest {
			return false, nil
		}
		if r.Owner.Sequence <= state.RetiredWUASequence {
			return false, ErrConsumed
		}
		for i, v := range state.Entries {
			if v.Owner != r.Owner || v.Reservation != r.Reservation {
				continue
			}
			if v.Phase != "released" || v.ReceiptDigest != digest(r) || v.CompletedAt != r.CompletedAt || v.ProofDigest != actionpermit.Digest([]byte(r.proof)) {
				return false, ErrUncertain
			}
			state.RetiredWUASequence = r.Owner.Sequence
			state.RetiredWUAReceiptDigest = digest(r)
			state.RetiredWUADigest = actionpermit.Digest([]byte("Tracebolt retired Windows WUA owner v4\x00" + state.RetiredWUADigest + "\x00" + digest(v)))
			state.Entries = append(state.Entries[:i], state.Entries[i+1:]...)
			return true, nil
		}
		return false, ErrIntegrity
	})
}

func (r Roster) ReusableMSI() bool {
	return r.Version == ReusableRosterVersion || r.BackgroundWUA()
}
func (r Roster) ReusableWUA() bool   { return r.Version == ReusableWUARosterVersion }
func (r Roster) BackgroundWUA() bool { return r.Version == BackgroundRosterVersion || r.ReusableWUA() }

func planStateVersion(v string) string {
	switch v {
	case "":
		return Version
	case ReusablePlanVersion:
		return ReusableVersion
	case BackgroundPlanVersion:
		return BackgroundVersion
	case ReusableWUAPlanVersion:
		return ReusableWUAVersion
	}
	return "invalid"
}
func activationStateVersion(v string) string {
	switch v {
	case "":
		return Version
	case ReusableActivationVersion:
		return ReusableVersion
	case BackgroundActivationVersion:
		return BackgroundVersion
	case ReusableWUAActivationVersion:
		return ReusableWUAVersion
	}
	return "invalid"
}
