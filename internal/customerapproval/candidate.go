// Package customerapproval defines a source-only candidate for a reviewed
// customer-device binding. It has no storage, network endpoint, enrollment,
// certificate, activation, collection or device action authority.
package customerapproval

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"time"

	"localrmm/internal/customerclaim"
	"localrmm/internal/customerpending"
	"localrmm/internal/enrollmentcrypto"
)

const Version = "tracebolt.customer-approval-candidate.v1"
const maxTimestamp = int64(253402300499)
const maxCandidateBytes = 8192

var ErrInvalid = errors.New("customer approval candidate invalid")

// Decision contains explicit human review affirmations. DeviceID must be freshly
// generated by trusted manager code and never accepted from an untrusted device.
type Decision struct {
	OperationID, DeviceID             string
	Acknowledged, FingerprintCompared bool
}

// Candidate is a public data contract, not proof that an operator reviewed the
// identity or that any authority exists. Pending holds no raw CSR or signature.
type Candidate struct {
	Version          string                 `json:"version"`
	ManagerDigest    string                 `json:"managerDigest"`
	CustomerRevision uint64                 `json:"customerRevision"`
	OperationID      string                 `json:"operationId"`
	DeviceID         string                 `json:"deviceId"`
	ConfirmedAt      int64                  `json:"confirmedAt"`
	Pending          customerpending.Record `json:"pending"`
}

// Build constructs a candidate from an exact reviewed snapshot and explicit
// acknowledgements. The snapshot is not itself a lease: the integrating caller
// must acquire and hold the real ReviewLease through the enrollment COMMIT,
// recheck it and the current session/issuer/clock at the commit edge, and bind
// the saved candidate to issuance in that same authoritative transaction.
// Failed or uncertain writes require guarded read-only reconciliation. The
// enrollment store must enforce global claim/key/device/operation deduplication.
func Build(e customerpending.ReviewExpectation, p customerpending.Record, d Decision, now time.Time) (Candidate, error) {
	if !d.Acknowledged || !d.FingerprintCompared || !enrollmentcrypto.ValidID(d.OperationID, "request_") || !enrollmentcrypto.ValidID(d.DeviceID, "agent_") ||
		!enrollmentcrypto.ValidHash(e.ManagerDigest) || e.CustomerRevision == 0 || e.CustomerRevision > 1<<53-1 ||
		e.ManagerID != p.ManagerID || e.CustomerID != p.CustomerID || e.InstallerProfileID != p.InstallerProfileID || e.ClaimID != p.ClaimID || e.ClaimHash != p.ClaimHash || e.KeyFingerprint != p.KeyFingerprint || e.DeadlineAt != p.DeadlineAt {
		return Candidate{}, ErrInvalid
	}
	c := Candidate{Version: Version, ManagerDigest: e.ManagerDigest, CustomerRevision: e.CustomerRevision, OperationID: d.OperationID, DeviceID: d.DeviceID, ConfirmedAt: now.UTC().Unix(), Pending: p}
	c.Pending.PublicKeyDER = bytes.Clone(p.PublicKeyDER)
	if !Valid(c) {
		return Candidate{}, ErrInvalid
	}
	return c, nil
}

// Valid checks consistency only. It cannot authenticate data, detect a replay,
// determine current authority or prove that a durable transition occurred.
func Valid(c Candidate) bool {
	p := c.Pending
	if c.Version != Version || !enrollmentcrypto.ValidHash(c.ManagerDigest) || c.CustomerRevision == 0 || c.CustomerRevision > 1<<53-1 || !enrollmentcrypto.ValidID(c.OperationID, "request_") || !enrollmentcrypto.ValidID(c.DeviceID, "agent_") ||
		p.Version != "tracebolt.customer-pending.v1" || p.CreatedAt <= 0 || p.CreatedAt > maxTimestamp-int64(customerpending.PendingLifetime/time.Second) || p.DeadlineAt != p.CreatedAt+int64(customerpending.PendingLifetime/time.Second) || c.ConfirmedAt < p.CreatedAt || c.ConfirmedAt >= p.DeadlineAt || c.ConfirmedAt > maxTimestamp {
		return false
	}
	m := customerclaim.Metadata{ManagerID: p.ManagerID, CustomerID: p.CustomerID, InstallerProfileID: p.InstallerProfileID, Origin: p.Origin, AgentOrigin: p.AgentOrigin, IssuerFingerprint: p.IssuerFingerprint, ClaimID: p.ClaimID, RequestID: p.RequestID, KeyFingerprint: p.KeyFingerprint, CSRHash: p.CSRHash, ClaimHash: p.ClaimHash, ComparisonCode: p.ComparisonCode}
	return customerclaim.ValidateStoredMetadata(m, p.PublicKeyDER)
}

// Canonical encodes a valid public candidate. The digest/bytes do not establish
// authenticity or permit certificate signing; no private key is accepted.
func Canonical(c Candidate) ([]byte, error) {
	if !Valid(c) {
		return nil, ErrInvalid
	}
	raw, err := json.Marshal(c)
	if err != nil || len(raw) > maxCandidateBytes {
		return nil, ErrInvalid
	}
	return raw, nil
}

// Parse requires exactly the canonical bytes, rejecting unknown/duplicate JSON
// fields and noncanonical encodings. This is still untrusted data until the
// owning transaction has authenticated, retained and rechecked its binding.
func Parse(raw []byte) (Candidate, error) {
	var c Candidate
	if len(raw) == 0 || len(raw) > maxCandidateBytes || json.Unmarshal(raw, &c) != nil {
		return Candidate{}, ErrInvalid
	}
	canonical, err := Canonical(c)
	if err != nil || !bytes.Equal(raw, canonical) {
		return Candidate{}, ErrInvalid
	}
	return c, nil
}

// Digest binds the exact canonical candidate under its own domain. A digest is
// a comparison value, not an authenticity check or an authorization token.
func Digest(c Candidate) (string, error) {
	raw, err := Canonical(c)
	if err != nil {
		return "", err
	}
	h := sha256.New()
	_, _ = h.Write([]byte("tracebolt.customer-approval-candidate.v1\x00"))
	_, _ = h.Write(raw)
	return hex.EncodeToString(h.Sum(nil)), nil
}
