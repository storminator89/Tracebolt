func TestServiceStartupBudgetKeepsBindingAndAge(t *testing.T) {
	s := startupTestSnapshot()
	s.RequestedCount = 128
	s.Rows = []ServiceStartupRow{}
	for i := 0; i < 128; i++ {
		row := startupTestRow("automatic", new(bool))
		row.ServiceIndex = uint32(i)
		s.Rows = append(s.Rows, row)
	}
	fitted, err := FitServiceStartupBudget(s, ServiceStartupMaxBytes)
	if err != nil || ValidateServiceStartup(fitted) != nil || !fitted.Truncated || len(fitted.Rows) >= 128 {
		t.Fatal(len(fitted.Rows), err)
	}
	b, _ := json.Marshal(fitted)
	if len(b) > ServiceStartupMaxBytes || fitted.RequestedCount != 128 || fitted.ServicesSHA256 != s.ServicesSHA256 || fitted.CollectedAt != s.CollectedAt || fitted.GenerationID != s.GenerationID || fitted.GrantID != s.GrantID {
		t.Fatal("fitting changed original binding")
	}
	if len(s.Rows) != 128 || s.Truncated {
		t.Fatal("mutated input")
	}
	*fitted.Rows[0].StartupMode = "disabled"
	if *s.Rows[0].StartupMode != "automatic" {
		t.Fatal("shared pointer after fitting")
	}
	if _, err := FitServiceStartupBudget(s, 1); err == nil {
		t.Fatal("impossible budget accepted")
	}
}

func TestServiceStartupCollectionBoundsAndCancellation(t *testing.T) {
	services := startupTestServices()
	reads, clocks := 0, 0
	read := func(_ context.Context, name string) (ServiceStartupRow, error) {
		if name != services[reads].Name {
			t.Fatal("not exact base row")
		}
		reads++
		return startupTestRow("manual", nil), nil
	}
	clock := func() time.Time { clocks++; return startupTestAt.Add(time.Second) }
	s, err := CollectServiceStartupWithReaderAndClock(context.Background(), services, startupTestGeneration, startupTestGrant, startupTestAt, read, clock)
	if err != nil || reads != 2 || clocks != 1 || s.CollectedAt != startupTestAt.Add(time.Second) || s.RequestedCount != 2 || s.Rows[1].ServiceIndex != 1 {
		t.Fatal(s, err, reads, clocks)
	}
	for _, input := range [][]Service{nil, make([]Service, 129), {{Name: "bad\x00name", State: "running"}}} {
		if _, err := CollectServiceStartupWithReaderAndClock(context.Background(), input, startupTestGeneration, startupTestGrant, startupTestAt, read, clock); err == nil {
			t.Fatal("invalid input")
		}
	}
	if reads != 2 || clocks != 1 {
		t.Fatal("input validation performed reads or consulted clock")
	}
	if _, err := CollectServiceStartupWithReaderAndClock(context.Background(), services, startupTestGeneration, startupTestGrant, startupTestAt, read, func() time.Time { return startupTestAt.Add(-time.Second) }); err == nil || reads != 2 {
		t.Fatal("clock regression read or clamped")
	}
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	if _, err := CollectServiceStartupWithReaderAndClock(ctx, services, startupTestGeneration, startupTestGrant, startupTestAt, read, clock); !errors.Is(err, context.Canceled) {
		t.Fatal(err)
	}
	ctx, cancel = context.WithCancel(context.Background())
	defer cancel()
	if _, err := CollectServiceStartupWithReaderAndClock(ctx, services, startupTestGeneration, startupTestGrant, startupTestAt, func(context.Context, string) (ServiceStartupRow, error) {
		cancel()
		return startupTestRow("manual", nil), nil
	}, clock); !errors.Is(err, context.Canceled) {
		t.Fatal("caller cancellation lost", err)
	}
	factoryCalls := 0
	factory := func(context.Context) (ServiceStartupReader, func(), error) {
		factoryCalls++
		return read, func() {}, nil
	}
	s, err = collectServiceStartupUsing(context.Background(), services, startupTestGeneration, startupTestGrant, startupTestAt, factory, 0, clock)
	if err != nil || factoryCalls != 0 || len(s.Rows) != 2 || s.Rows[0].StartupQuality != "unavailable" {
		t.Fatal("expired budget queried native or lost row", s, err)
	}
	closed, attempts := 0, 0
	factory = func(context.Context) (ServiceStartupReader, func(), error) {
		return func(ctx context.Context, _ string) (ServiceStartupRow, error) {
			attempts++
			<-ctx.Done()
			return startupTestRow("manual", nil), nil
		}, func() { closed++ }, nil
	}
	s, err = collectServiceStartupUsing(context.Background(), services, startupTestGeneration, startupTestGrant, startupTestAt, factory, time.Millisecond, clock)
	if err != nil || closed != 1 || attempts != 1 || s.Rows[0].StartupQuality != "unavailable" || s.Rows[1].StartupQuality != "unavailable" {
		t.Fatal("cooperative exhaustion", s, err, closed, attempts)
	}
}

func TestServiceStartupFailuresAreFiniteAndEmptyDoesNotRead(t *testing.T) {
	clock := func() time.Time { return startupTestAt }
	for _, err := range []error{ErrServiceStartupDenied, ErrServiceStartupUnsupported, errors.New("private path C:\\secret; account password")} {
		s, e := CollectServiceStartupWithReaderAndClock(context.Background(), startupTestServices(), startupTestGeneration, startupTestGrant, startupTestAt, func(context.Context, string) (ServiceStartupRow, error) { return ServiceStartupRow{}, err }, clock)
		if e != nil || ValidateServiceStartup(s) != nil {
			t.Fatal(s, e)
		}
		want := "unavailable"
		if err == ErrServiceStartupDenied {
			want = "denied"
		}
		if s.Rows[0].StartupQuality != want {
			t.Fatal(s)
		}
		b, _ := json.Marshal(s)
		if bytes.Contains(b, []byte("secret")) || bytes.Contains(b, []byte("password")) {
			t.Fatal("unsanitized error")
		}
	}
	factory := func(context.Context) (ServiceStartupReader, func(), error) {
		t.Fatal("empty array invoked factory")
		return nil, nil, nil
	}
	s, err := collectServiceStartupUsing(context.Background(), []Service{}, startupTestGeneration, startupTestGrant, startupTestAt, factory, serviceStartupCollectionBudget, clock)
	if err != nil || s.RequestedCount != 0 || s.Rows == nil || s.Truncated || ValidateServiceStartup(s) != nil {
		t.Fatal(s, err)
	}
}

func FuzzDecodeServiceStartup(f *testing.F) {
	b, _ := EncodeServiceStartup(startupTestSnapshot())
	f.Add(b)
	f.Add([]byte(`{"schemaVersion":"tracebolt.windows-service-startup.v1"}`))
	f.Fuzz(func(t *testing.T, raw []byte) {
		s, err := DecodeServiceStartup(raw)
		if err != nil {
			return
		}
		if err := ValidateServiceStartup(s); err != nil {
			t.Fatal("decoded invalid snapshot", err)
		}
		encoded, err := EncodeServiceStartup(s)
		if err != nil || !bytes.Equal(encoded, raw) {
			t.Fatal("noncanonical bytes admitted", err)
		}
	})
}
