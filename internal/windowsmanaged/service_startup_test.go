func startupTestRow(mode string, delayed *bool) ServiceStartupRow {
	r := ServiceStartupRow{StartupMode: &mode, StartupQuality: "observed", DelayedAutoStart: delayed, DelayedAutoQuality: "not-applicable"}
	if mode == "automatic" {
		r.DelayedAutoQuality = "observed"
	}
	return r
}
func startupTestSnapshot() ServiceStartupSnapshot {
	services := startupTestServices()
	digest, _ := ServiceStartupRowsSHA256(services)
	b := false
	rows := []ServiceStartupRow{startupTestRow("automatic", &b), startupTestRow("manual", nil)}
	rows[1].ServiceIndex = 1
	return ServiceStartupSnapshot{SchemaVersion: ServiceStartupSchemaVersion, Scope: ServiceStartupScope, GrantID: startupTestGrant, GenerationID: startupTestGeneration, ServicesSHA256: digest, CollectedAt: startupTestAt, RequestedCount: 2, Rows: rows}
}

func TestServiceStartupConsentCanonicalAndIndependent(t *testing.T) {
	binding := strings.Repeat("a", 64)
	c := ServiceStartupConsent{ServiceStartupConsentVersion, ServiceStartupScope, binding, startupTestGrant, false}
	raw, err := EncodeServiceStartupConsent(c, binding)
	if err != nil {
		t.Fatal(err)
	}
	got, err := DecodeServiceStartupConsent(raw, binding)
	if err != nil || got != c || got.Enabled {
		t.Fatal(got, err)
	}
	for _, bad := range [][]byte{
		bytes.Replace(raw, []byte(ServiceStartupScope), []byte(CollectionProfile), 1),
		bytes.Replace(raw, []byte(ServiceStartupConsentVersion), []byte("tracebolt.windows-inventory-consent.v1"), 1),
		bytes.Replace(raw, []byte(`"enabled":false`), []byte(`"enabled":null`), 1),
		bytes.Replace(raw, []byte(`"enabled":false`), []byte(`"enabled":false,"enabled":false`), 1),
		bytes.Replace(raw, []byte(`,"enabled":false`), nil, 1),
		append(append([]byte{}, raw...), '\n'),
	} {
		if _, err := DecodeServiceStartupConsent(bad, binding); !errors.Is(err, ErrServiceStartupInvalid) {
			t.Fatalf("accepted %s: %v", bad, err)
		}
	}
	if _, err := DecodeServiceStartupConsent(raw, strings.Repeat("b", 64)); err == nil {
		t.Fatal("unbound consent")
	}
	c.Enabled = true
	if _, err := EncodeServiceStartupConsent(c, binding); err != nil {
		t.Fatal(err)
	}
}

func TestServiceStartupRowsDigestExactBase(t *testing.T) {
	rows := startupTestServices()
	digest, err := ServiceStartupRowsSHA256(rows)
	b, _ := json.Marshal(rows)
	expected := sha256.Sum256(b)
	if err != nil || digest != hex.EncodeToString(expected[:]) {
		t.Fatal(digest, err)
	}
	mutations := []func([]Service){
		func(s []Service) { s[0], s[1] = s[1], s[0] },
		func(s []Service) { s[0].Name = "different" },
		func(s []Service) { s[0].DisplayName = "different" },
		func(s []Service) { s[0].State = "stopped" },
		func(s []Service) { s[0].PID++ },
	}
	for _, mutate := range mutations {
		copy := append([]Service{}, rows...)
		mutate(copy)
		changed, err := ServiceStartupRowsSHA256(copy)
		if err != nil || changed == digest {
			t.Fatal("digest failed to bind complete ordered base", err)
		}
	}
	empty, err := ServiceStartupRowsSHA256([]Service{})
	emptyHash := sha256.Sum256([]byte("[]"))
	if err != nil || empty != hex.EncodeToString(emptyHash[:]) {
		t.Fatal(empty, err)
	}
	if _, err := ServiceStartupRowsSHA256(nil); err == nil {
		t.Fatal("nil array accepted")
	}
	if _, err := ServiceStartupRowsSHA256(make([]Service, 129)); err == nil {
		t.Fatal("oversize accepted")
	}
}

// The shared file is generated by this Go test, not a second-language JSON or
// hashing implementation. To deliberately refresh the synthetic fixture, run
// TRACEBOLT_UPDATE_SERVICE_STARTUP_FIXTURE=1 go test ./internal/windowsmanaged
// -run '^TestServiceStartupGoGeneratedDigestFixture$'. Ordinary tests only read.
func TestServiceStartupGoGeneratedDigestFixture(t *testing.T) {
	type vector struct {
		Name          string    `json:"name"`
		Services      []Service `json:"services"`
		CanonicalJSON string    `json:"canonicalJSON"`
		SHA256        string    `json:"sha256"`
		ValidBase     bool      `json:"validBase"`
	}
	unicodeRows := []Service{
		{Name: "Dienst-ä-&<β>", DisplayName: "日本語 🚀 \"quoted\" \\ path", State: "stopped", PID: 0},
		{Name: "Дубликат", DisplayName: "A&B > C", State: "paused", PID: 4294967295},
	}
	duplicate := Service{Name: "same", DisplayName: "duplicate", State: "running", PID: 4}
	cases := []vector{
		{Name: "empty", Services: []Service{}, ValidBase: true},
		{Name: "ascii", Services: []Service{{Name: "FixtureService", DisplayName: "Fixture Service", State: "running", PID: 44}}, ValidBase: true},
		{Name: "unicode-html", Services: unicodeRows, ValidBase: true},
		{Name: "duplicates", Services: []Service{duplicate, duplicate}, ValidBase: true},
		{Name: "canonical-escapes-only", Services: []Service{{Name: "line\u2028separator", DisplayName: "paragraph\u2029separator", State: "running", PID: 1}}, ValidBase: false},
		{Name: "unicode-trimmed", Services: unicodeRows[:1], ValidBase: true},
		{Name: "unicode-reordered", Services: []Service{unicodeRows[1], unicodeRows[0]}, ValidBase: true},
	}
	for i := range cases {
		b, err := json.Marshal(cases[i].Services)
		if err != nil {
			t.Fatal(err)
		}
		sum := sha256.Sum256(b)
		cases[i].CanonicalJSON = string(b)
		cases[i].SHA256 = hex.EncodeToString(sum[:])
		got, err := ServiceStartupRowsSHA256(cases[i].Services)
		if cases[i].ValidBase {
			if err != nil || got != cases[i].SHA256 {
				t.Fatal(cases[i].Name, got, err)
			}
		} else if err == nil {
			t.Fatal("v1-invalid labels accepted")
		}
	}
	want, err := json.MarshalIndent(cases, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	want = append(want, '\n')
	const path = "../../web/src/windows-service-startup-go-fixture.json"
	if os.Getenv("TRACEBOLT_UPDATE_SERVICE_STARTUP_FIXTURE") == "1" {
		if err := os.WriteFile(path, want, 0644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatal("Go-generated shared digest fixture differs; regenerate explicitly and review")
	}
}

